import { stripVTControlCharacters } from "node:util";
import StyleDictionary from "style-dictionary";
import type { DesignTokens, TransformedToken } from "style-dictionary/types";
import { customPropertyName, isRecord, referencesOf, tokenKind } from "./reference.js";
import { filesOfTheme, tokensOfTheme } from "./resolve.js";
import { checkTokenSet } from "./rules.js";
import type { TokenDefinition, TokenFinding, TokenSet } from "./types.js";

/** The comment the generated CSS starts with. It names no path, version or time, so the output is stable. */
export const tokenCssHeader = `/*
 * Generated by \`fazon sync\` from the token set. Do not edit this file:
 * change the token set and run \`fazon sync\`.
 */
`;

export interface BuildTokensOptions {
  /** `tokens.prefix` from fazon.yaml: lowercase kebab-case, or empty (the default) for none. */
  readonly prefix?: string;
}

/** One token as the checks see it in one theme. */
export interface IndexedToken {
  /** The dotted path. */
  readonly path: string;
  /** The custom property name, with `--` and the prefix. */
  readonly name: string;
  readonly kind: "raw" | "role";
  readonly type: string;
  /** The dotted paths the value references: the one a role points at, or a shadow's colours. */
  readonly references: readonly string[];
  /** The value with every reference resolved, in CSS: `#2154d9`, `0.875rem`, `0.1s`. */
  readonly resolvedValue: string;
}

/** The token set's custom properties per theme, for `spec check` (SPEC-011) and the `tokens` check. */
export interface TokenIndex {
  readonly prefix: string;
  readonly themes: readonly string[];
  readonly defaultTheme: string;
  /** Per theme, each custom property name's token, every token of the theme. */
  readonly byTheme: ReadonlyMap<string, ReadonlyMap<string, IndexedToken>>;
  /** The role tokens' dotted paths, which are the same in every theme. */
  readonly roleTokens: readonly string[];
}

export interface TokenBuild {
  /** The token CSS (docs/spec/tokens.md#the-build). */
  readonly css: string;
  readonly index: TokenIndex;
  /** Style Dictionary's warnings other than the expected one about a theme block's references. */
  readonly warnings: readonly string[];
}

/** Thrown when the token set breaks a TOKEN rule; the build refuses it. */
export class TokenSetError extends Error {
  readonly findings: readonly TokenFinding[];
  constructor(findings: readonly TokenFinding[]) {
    super(`The token set breaks the TOKEN rules:\n${findings.map((f) => `  ${f.rule} ${f.message}`).join("\n")}`);
    this.name = "TokenSetError";
    this.findings = findings;
  }
}

const prefixPattern = /^([a-z0-9]+(-[a-z0-9]+)*)?$/;
const filteredReferencesWarning = "filtered out token references were found";
const filteredReferencesList = "Here are the references that are used but not defined in the file:";

/**
 * Builds the token set: Style Dictionary once per theme, assembled into one CSS file. `:root` holds
 * every raw token, every theme-independent role and the default theme's roles; then each theme,
 * the default first, gets a `[data-theme="<theme>"]` block with its own role tokens, so a subtree
 * can switch to any theme. Also returns the index of every theme's custom properties. Refuses a set
 * that breaks a TOKEN rule. Themes are built one after another: Style Dictionary keeps its
 * messages in module state.
 */
export async function buildTokens(tokenSet: TokenSet, options: BuildTokensOptions = {}): Promise<TokenBuild> {
  const prefix = options.prefix ?? "";
  if (!prefixPattern.test(prefix)) throw new Error(`The token prefix "${prefix}" is not lowercase kebab-case.`);
  const findings = checkTokenSet(tokenSet);
  if (findings.length > 0) throw new TokenSetError(findings);

  const others = tokenSet.themes.filter((t) => t !== tokenSet.defaultTheme);
  const blocks: string[] = [];
  const warnings: string[] = [];
  const byTheme = new Map<string, ReadonlyMap<string, IndexedToken>>();
  for (const theme of [tokenSet.defaultTheme, ...others]) {
    const built = await buildTheme(tokenSet, theme, prefix, theme === tokenSet.defaultTheme);
    blocks.push(...built.blocks);
    warnings.push(...built.warnings);
    byTheme.set(theme, built.index);
  }

  const defaults = tokensOfTheme(tokenSet, tokenSet.defaultTheme);
  return {
    css: [tokenCssHeader, ...blocks].join("\n"),
    index: {
      prefix,
      themes: tokenSet.themes,
      defaultTheme: tokenSet.defaultTheme,
      byTheme,
      roleTokens: [...defaults.values()].filter((t) => tokenKind(t) === "role").map((t) => t.path),
    },
    warnings,
  };
}

/** The token CSS alone (`buildTokens(...).css`). */
export async function buildTokenCss(tokenSet: TokenSet, options: BuildTokensOptions = {}): Promise<string> {
  return (await buildTokens(tokenSet, options)).css;
}

/** The index of the token set's custom properties alone (`buildTokens(...).index`). */
export async function indexTokens(tokenSet: TokenSet, options: BuildTokensOptions = {}): Promise<TokenIndex> {
  return (await buildTokens(tokenSet, options)).index;
}

interface ThemeBuild {
  /** The default theme's `:root` block and its theme block, or another theme's block. */
  blocks: string[];
  warnings: string[];
  index: Map<string, IndexedToken>;
}

/**
 * Runs Style Dictionary on one theme's merged tokens and formats its CSS blocks: for the default
 * theme, `:root` with every token; for every theme, a block filtered to its context's own tokens.
 * The dictionary, and so the index, keeps every token.
 */
async function buildTheme(tokenSet: TokenSet, theme: string, prefix: string, isDefault: boolean): Promise<ThemeBuild> {
  const tokens = tokensOfTheme(tokenSet, theme);
  const own = new Set(
    filesOfTheme(tokenSet, theme)
      .flatMap((f) => (f.source.kind === "theme" ? f.tokens : []))
      .map((t) => t.path),
  );
  const block = (selector: string, only?: ReadonlySet<string>) => ({
    destination: "tokens.css",
    format: "css/variables",
    emitEmptyFiles: true,
    options: { outputReferences: true, showFileHeader: false, selector },
    ...(only === undefined ? {} : { filter: (token: TransformedToken) => only.has(token.path.join(".")) }),
  });
  const sd = new StyleDictionary(
    {
      tokens: toTree(tokens.values()),
      usesDtcg: true,
      // Anything Style Dictionary would only print while reading and transforming is an error here.
      log: { warnings: "error", verbosity: "verbose", errors: { brokenReferences: "throw" } },
      platforms: {
        css: {
          transformGroup: "css",
          prefix,
          // The format's warnings come back in its logs (formatFile prints nothing).
          log: { warnings: "warn", verbosity: "verbose" },
          files: [...(isDefault ? [block(":root")] : []), block(`[data-theme="${theme}"]`, own)],
        },
      },
    },
    { verbosity: "verbose", warnings: "error" },
  );
  await sd.hasInitialized;
  const platform = sd.getPlatformConfig("css");
  const dictionary = await sd.getPlatformTokens("css");
  const blocks: string[] = [];
  const warnings: string[] = [];
  for (const file of platform.files ?? []) {
    const { output, logs } = await sd.formatFile(file, platform, dictionary);
    if (typeof output !== "string") throw new Error(`Style Dictionary built no CSS for the theme ${theme}.`);
    blocks.push(output);
    const expected = file.filter === undefined ? new Set<string>() : referencesOutside(tokens, own);
    warnings.push(
      ...logs.warning.map((w) => stripVTControlCharacters(w)).filter((w) => !isExpectedFilterWarning(w, expected)),
    );
  }
  if (blocks.length !== (isDefault ? 2 : 1)) throw new Error("Style Dictionary lost the platform's files.");

  const index = new Map<string, IndexedToken>();
  for (const transformed of dictionary.allTokens) {
    const path = transformed.path.join(".");
    const name = customPropertyName(path, prefix);
    if (`--${transformed.name}` !== name) {
      throw new Error(`Style Dictionary named ${path} --${transformed.name}, not ${name}.`);
    }
    const token = tokens.get(path);
    if (token === undefined) throw new Error(`Style Dictionary built ${path}, which the token set doesn't define.`);
    const value: unknown = transformed.$value;
    index.set(name, {
      path,
      name,
      kind: tokenKind(token),
      type: token.type,
      references: referencesOf(token).map((r) => r.target),
      resolvedValue: typeof value === "string" ? value : JSON.stringify(value),
    });
  }
  return { blocks, warnings, index };
}

/** The tokens a theme block references without containing them; they are in `:root`. */
function referencesOutside(tokens: ReadonlyMap<string, TokenDefinition>, only: ReadonlySet<string>): Set<string> {
  const outside = new Set<string>();
  for (const path of only) {
    const token = tokens.get(path);
    if (token === undefined) continue;
    for (const { target } of referencesOf(token)) if (!only.has(target)) outside.add(target);
  }
  return outside;
}

/**
 * A theme block references tokens it doesn't contain, so Style Dictionary warns about filtered-out
 * references. That warning is expected when it lists exactly those references; anything else is kept.
 */
export function isExpectedFilterWarning(warning: string, expected: ReadonlySet<string>): boolean {
  if (expected.size === 0 || !warning.includes(filteredReferencesWarning)) return false;
  const lines = warning.split("\n");
  const start = lines.indexOf(filteredReferencesList);
  if (start < 0) return false;
  const listed = new Set<string>();
  for (const line of lines.slice(start + 1)) {
    if (!line.startsWith("    ")) break;
    listed.add(line.trim());
  }
  return listed.size === expected.size && [...listed].every((r) => expected.has(r));
}

/** The nested DTCG tree Style Dictionary reads, from merged tokens: `$type` and `$value` only. */
function toTree(tokens: Iterable<TokenDefinition>): DesignTokens {
  const tree: Record<string, unknown> = {};
  for (const token of tokens) {
    const segments = token.path.split(".");
    const name = segments.pop();
    if (name === undefined) continue;
    let group = tree;
    for (const segment of segments) {
      const existing = group[segment];
      const next: Record<string, unknown> = isRecord(existing) ? existing : {};
      group[segment] = next;
      group = next;
    }
    group[name] = { $type: token.type, $value: structuredClone(token.value) };
  }
  return tree as DesignTokens;
}
